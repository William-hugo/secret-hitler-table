// "How to play" slides, shared by the TV (big) and the phones (compact).
// Each slide: title, points (short sentences, read out loud by whoever explains), visual (HTML).
function guideSlides(n) {
  const T = { 5: [3, 1], 6: [4, 1], 7: [4, 2], 8: [5, 2], 9: [5, 3], 10: [6, 3] };
  const count = T[n] ? n : null;
  const img = (f, cls = '', style = '') => `<img class="${cls}" src="/assets/${f}" alt="" style="${style}">`;
  const table = `<table class="gtable"><tr><th>Players</th>${[5, 6, 7, 8, 9, 10].map((k) => `<th class="${k === count ? 'hl' : ''}">${k}</th>`).join('')}</tr>
    <tr><td>Liberals</td>${[5, 6, 7, 8, 9, 10].map((k) => `<td class="${k === count ? 'hl' : ''}">${T[k][0]}</td>`).join('')}</tr>
    <tr><td>Fascists</td>${[5, 6, 7, 8, 9, 10].map((k) => `<td class="${k === count ? 'hl' : ''}">${T[k][1]}</td>`).join('')}</tr>
    <tr><td>Hitler</td>${[5, 6, 7, 8, 9, 10].map((k) => `<td class="${k === count ? 'hl' : ''}">1</td>`).join('')}</tr></table>`;
  const board = !count || count <= 6 ? '5-6' : count <= 8 ? '7-8' : '9-10';
  const power = (p, name, txt) => `<div class="gpow">${img('power-' + p + '.svg')}<b>${name}</b><span>${txt}</span></div>`;
  return [
    { title: 'Welcome to Secret Hitler',
      points: ['It is 1930s Germany. Two teams fight for control of the government: the Liberals and the Fascists.',
        'One Fascist is secretly Hitler.',
        'The Liberals are the majority, but nobody knows who is who. The Fascists know each other and try to fool everyone.',
        'You win by passing laws (policies) and by finding, or protecting, Hitler.'],
      visual: `<div class="gfan">${img('role-liberal-3.png')}${img('role-hitler.png')}${img('role-fascist-2.png')}</div>` },
    { title: 'Your phone is your card',
      points: ['At the start, your phone gives you a sealed envelope.',
        'Press and hold it to see your secret role card and your party membership card. Let go to hide it.',
        'Never show your screen to anyone. You may say whatever you like about your role, true or false.',
        'Your phone is also your ballot (Ja! / Nein) and your hand of policy cards when you are in power.'],
      visual: `<div class="gfan">${img('role-envelope-front.png')}${img('role-liberal-5.png')}${img('party-membership-liberal.png')}</div>` },
    { title: count ? `The teams for ${count} players` : 'The teams',
      points: [count ? `This table: ${T[count][0]} Liberals, ${T[count][1]} Fascist${T[count][1] > 1 ? 's' : ''} and Hitler.` : 'The number of each role depends on how many people play.',
        'Fascists always know who the other Fascists are and who Hitler is.',
        count && count >= 7 ? 'With 7–10 players, Hitler does NOT know who the Fascists are.' : 'With 5–6 players, Hitler also knows who the Fascist is. With 7–10, Hitler is in the dark.',
        'Liberals know nothing except their own card.'],
      visual: table },
    { title: 'The night phase',
      points: ['After everyone has seen their role, the TV narrator runs the opening ritual.',
        'Put your phones down. Everyone closes their eyes when told.',
        'The Fascists (and in small games, Hitler) open their eyes to see each other, then close them again.',
        'Stay silent until the narrator is done.'],
      visual: `<div class="gnight"><div class="gmoon"></div></div>` },
    { title: 'How to win',
      points: ['Liberals win by passing 5 Liberal policies, or by executing Hitler.',
        'Fascists win by passing 6 Fascist policies…',
        '…or by getting Hitler elected Chancellor after 3 Fascist policies have been passed.',
        'The two boards on the TV track the policies.'],
      visual: `<div class="gboards">${img('board-liberal.png')}${img('board-fascist-' + board + '.png')}</div>` },
    { title: 'The policy deck is stacked',
      points: ['The deck has 17 policies: 6 Liberal and 11 Fascist.',
        'So even honest Liberals sometimes have no choice but to pass a Fascist policy.',
        'That is where the lying and the suspicion come from: "I only got Fascist cards, I swear!"',
        'When fewer than 3 cards are left, the discard pile is shuffled back in.'],
      visual: `<div class="gdeck">${Array.from({ length: 6 }, () => img('policy-liberal.png')).join('')}${Array.from({ length: 11 }, () => img('policy-fascist.png')).join('')}</div>` },
    { title: 'Each round: the election',
      points: ['The presidency moves clockwise around the table each round.',
        'The Presidential Candidate nominates a Chancellor. Talk it over first!',
        'Term limits: the last elected President and Chancellor can\'t be nominated as Chancellor (with only 5 players left alive, just the last Chancellor).',
        'The TV shows who is President, the nominee, and who is term-limited.'],
      visual: `<div class="gplac"><div class="gp pres">President</div><div class="gp chan">Chancellor</div></div>` },
    { title: 'Everyone votes',
      points: ['Everyone, including the candidates, votes Ja! (yes) or Nein (no) on their phone.',
        'Votes stay hidden until the last vote is in, then all are revealed on the TV at once.',
        'More than half Ja! and the government is elected. A tie fails.',
        'Remember how people voted, it is the best clue you will get.'],
      visual: `<div class="gfan">${img('vote-yes.png')}${img('vote-no.png')}</div>` },
    { title: 'Failed votes and chaos',
      points: ['If the vote fails, the presidency moves to the next player and the election tracker moves one step.',
        'After 3 failed governments in a row, the country falls into chaos:',
        'the top policy of the deck is passed automatically, its power is ignored, and term limits reset.',
        'Chaos is bad for Liberals, because most of the deck is Fascist.'],
      visual: img('board-election-tracker.png', 'gwide') },
    { title: 'Passing a law: quiet time',
      points: ['The President secretly draws 3 policies, throws 1 away, and hands 2 to the Chancellor.',
        'The Chancellor throws 1 away and passes the other. It goes on the board.',
        'While this happens it is QUIET TIME: the President and Chancellor may not talk or signal.',
        'Afterwards anyone can claim what they saw. Anyone can lie.'],
      visual: `<div class="gleg"><div>${img('policy-fascist.png')}${img('policy-liberal.png')}${img('policy-fascist.png', 'gout')}</div><span>→</span><div>${img('policy-fascist.png')}${img('policy-liberal.png', 'gout2')}</div><span>→</span><div>${img('policy-fascist.png')}</div></div>` },
    { title: 'Presidential powers',
      points: ['Some Fascist policies give the President a one-time power. The TV shows it when it happens.',
        `On the ${board} player board the powers are printed on the Fascist track.`,
        'The President must use the power before the next round.',
        'After investigating or peeking, the President may tell everyone what they saw, or lie. Nobody can check.'],
      visual: `<div class="gpows">${power('investigate', 'Investigate', 'See one player\'s party card')}${power('special', 'Special election', 'Pick the next President')}${power('peek', 'Policy peek', 'See the top 3 policies')}${power('execute', 'Execution', 'Kill a player')}</div>` },
    { title: 'Hitler, executions and veto',
      points: ['Once 3 Fascist policies are passed, electing Hitler as Chancellor ends the game: Fascists win. Anyone else elected is marked "Not Hitler".',
        'Executed players are out: no talking, no voting. Their role stays secret, unless it was Hitler, then Liberals win.',
        'After 5 Fascist policies, the Chancellor can propose a veto. If the President agrees, both policies are thrown away (the tracker moves).',
        ''].filter(Boolean),
      visual: `<div class="gfan">${img('role-hitler.png')}${img('player-icon-hitler.png', '', 'width:7rem;align-self:center')}</div>` },
    { title: 'Talk time and quiet time',
      points: ['Watch the sign in the top-left of the TV.',
        'Green 💬 Talk time: argue, accuse, defend, make deals. Lying is part of the game.',
        'Red 🤫 Quiet time: no talking, during the night phase and while a government passes a policy.',
        'Liberals: follow the votes and the claims. Fascists: blend in. Hitler: act like the most loyal Liberal.'],
      visual: `<div class="gplac"><div class="gp talk">💬 Talk time</div><div class="gp quiet">🤫 Quiet time</div></div>` },
    { title: 'Ready to play!',
      points: ['Sit in a circle and join in seating order, clockwise.',
        'The host (★) or anyone at the TV starts the game.',
        'Hold your envelope, keep your role secret, and trust no one.',
        'Good luck, and may the best liars win.'],
      visual: `<div class="gfan">${img('victory-liberal-header.png', '', 'width:20rem')}${img('victory-fascist-header.png', '', 'width:20rem')}</div>` },
  ];
}
